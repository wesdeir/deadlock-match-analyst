import api
import analyst
import benchmarks
import extras

HERE = Path(__file__).parent
OUT = HERE / "docs" / "dashboard.html"


def game_data(m, names):
    mi = api.match_metadata(m["match_id"])["match_info"]
    analyst.derive_hero_codes(mi, names)
    analyst.derive_item_classes(mi, names)
    me = next(p for p in mi["players"] if p["account_id"] == analyst.ACCOUNT_ID)
    dur = mi["duration_s"]
    players = {p["player_slot"]: p for p in mi["players"]}
    paths = {p["player_slot"]: p for p in mi["match_paths"]["paths"]}
    team = [p for p in mi["players"] if p["team"] == me["team"]]
    foes = [p for p in mi["players"] if p["team"] != me["team"]]
    opp = [p for p in mi["players"] if p["assigned_lane"] == me["assigned_lane"] and p["team"] != me["team"]]
    mate = [p for p in mi["players"] if p["assigned_lane"] == me["assigned_lane"] and p["team"] == me["team"]]
    grid = list(range(0, dur, 60)) + [dur]
    series = {p["player_slot"]: analyst.nw_series(p) for p in mi["players"]}

    def gap(t):
        return (sum(analyst.interp(series[p["player_slot"]], t) for p in team)
                - sum(analyst.interp(series[p["player_slot"]], t) for p in foes))

    # damage taken from each enemy
    dmg = []
    for e in foes:
        pr = analyst.damage_profile(mi, e["player_slot"], me["player_slot"])
        dmg.append({"hero": names.hero(e["hero_id"]), "bullet": pr["Bullet"],
                    "ability": pr["Ability"] + pr["UnknownAbility"] + pr["Misc"], "melee": pr["Melee"]})
    dmg.sort(key=lambda d: -(d["bullet"] + d["ability"] + d["melee"]))
    res = {}
    for label, t in (("15:00", 900), ("25:00", 1500), ("end", dur)):
        b, s = analyst.resist_owned(me, min(t, dur), names)
        res[label] = {"bullet": b, "spirit": s}

    # souls by source
    gs = {extras.GOLD_SOURCES.get(g["source"], str(g["source"])): g["gold"] for g in me["stats"][-1]["gold_sources"]}

    # fights
    fights, _ = extras.find_fights(mi)
    dead = analyst.dead_intervals(mi)
    frows = []
    for f in fights:
        died = any(d[1] == me["player_slot"] for d in f)
        kill = any(d[3] == me["player_slot"] for d in f)
        if len(f) < 3 and not died and not kill:
            continue
        ours = sum(1 for d in f if d[2] == me["team"])
        theirs = len(f) - ours
        t0 = f[0][0]
        fx, fy = f[0][4]["x"], f[0][4]["y"]
        if died:
            pres = "died"
        elif any(a <= t0 - 10 < b for a, b in dead[me["player_slot"]]):
            pres = "dead"
        else:
            x, y = analyst.pos_at(paths[me["player_slot"]], t0 - 10)
            pres = "there" if math.hypot(x - fx, y - fy) <= 3000 else "away"
        frows.append({"t0": t0, "t1": f[-1][0], "res": "won" if theirs > ours else ("lost" if ours > theirs else "even"),
                      "theirs": theirs, "ours": ours, "pres": pres, "kill": kill,
                      "first": names.hero(players[f[0][1]]["hero_id"]), "firstus": players[f[0][1]]["team"] == me["team"]})

    # lane duo vs typical (benchmarks)
    lane = []
    try:
        lc = benchmarks.lane_curve(me["hero_id"], me["assigned_lane"])
    except api.RateLimited:
        lc = None
    if lc and opp and mate:
        for t, mean, sd in zip(lc["sample_times_s"], lc["net_worth_diff"], lc["net_worth_diff_std"]):
            if t > dur:
                break
            mine = sum(analyst.interp(series[p["player_slot"]], t) for p in mate) - sum(
                analyst.interp(series[p["player_slot"]], t) for p in opp)
            lane.append({"t": t, "mine": mine, "mean": mean, "sd": sd})

    deaths = []
    for dd in me["death_details"]:
        k = players.get(dd["killer_player_slot"])
        deaths.append({"t": dd["game_time_s"], "dur": dd.get("death_duration_s", 0),
                       "killer": names.hero(k["hero_id"]) if k else "creep/world",
                       "x": dd["death_pos"]["x"], "y": dd["death_pos"]["y"]})
    kills = sorted(dd["game_time_s"] for p in mi["players"] for dd in p["death_details"]
                   if dd["killer_player_slot"] == me["player_slot"])
    mb = [{"t": b["destroyed_time_s"], "mine": b["team_claimed"] == me["team"]} for b in (mi.get("mid_boss") or [])]
    hist = {"ranked_calibration_match": m["ranked_calibration_match"]}
    s = extras.game_summary(mi, me, names, hist)
    return {
        "n": m["ranked_calibration_match"], "match": mi["match_id"], "hero": names.hero(me["hero_id"]),
        "win": me["team"] == mi["winning_team"], "dur": dur, "lane": extras.lane_name(names, me["assigned_lane"]),
        "kda": s["kda"], "opp": [names.hero(p["hero_id"]) for p in opp],
        "nw": [{"t": t, "me": analyst.interp(series[me["player_slot"]], t),
                "opp": [analyst.interp(series[p["player_slot"]], t) for p in opp]} for t in grid],
        "gap": [[t, gap(t)] for t in grid], "deaths": deaths, "kills": kills, "midboss": mb,
        "dmg": dmg, "resist": res, "souls": gs, "fights": frows, "lane_duo": lane,
        "score": {k: s[k] for k in ("ld6", "ld9", "ld15", "td15", "d_early", "first_die", "deaths", "team_deaths", "spm", "bullet_pct")},
    }


def build():
    h = api.match_history(analyst.ACCOUNT_ID)
    cal = sorted(analyst.calibration_matches(h), key=lambda m: m["match_id"])
    names = analyst.Names()
    games = [game_data(m, names) for m in cal]
    OUT.parent.mkdir(exist_ok=True)
    html = TEMPLATE.replace("/*DATA*/null", json.dumps({"games": games}, separators=(",", ":")))
    OUT.write_text(html, encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB), {len(games)} games")


